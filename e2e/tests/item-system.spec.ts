import { expect, test } from '@playwright/test'

test('equipment and discovered keys persist without exposing closed contents', async ({ page }) => {
  test.setTimeout(60000)
  await page.goto('/')
  await page.getByTestId('username-input').fill('ItemAdmin')
  await page.getByTestId('password-input').fill('A long test-only passphrase1!')
  await page.getByTestId('login-button').click()
  await expect(page.getByText(/Online/)).toBeVisible()
  await expect(page.getByTestId('current-room')).toHaveText('Item Workshop')
  const input = page.getByTestId('command-input')
  const transcript = page.getByTestId('transcript')
  const inventory = page.getByTestId('inventory-panel')
  const send = async (command: string, expected: string | RegExp) => {
    const count = await transcript.locator('.transcript-line').count()
    await input.pressSequentially(command, { delay: 15 })
    await input.press('Enter')
    const reply = transcript.locator('.transcript-line').nth(count + 1)
    await expect(reply).toContainText(expected)
    return (await reply.textContent())!
  }
  await send('/item spawn clothing_backpack', 'Created')
  await send('take backpack', 'You take')
  await send('wear backpack', 'You wear')
  await send('/item spawn readable_letter', 'Created')
  await send('take letter', 'You take')
  await send('open backpack', 'You open')
  await send('put letter in backpack', 'You put')
  await send('close backpack', 'You close')
  await expect(inventory).not.toContainText('letter')
  await page.reload()
  await expect(page.getByText(/Online/)).toBeVisible()
  await expect(inventory).toContainText('leather backpack (back, closed)')
  await expect(inventory).not.toContainText('letter')
  await send('open backpack', 'You open')
  await expect(inventory).toContainText('folded letter')
  const chest = (await send('/item spawn container_chest_wooden', 'Created')).match(/[a-f0-9-]{36}/)![0]
  const rug = (await send('/item spawn furniture_rug', 'Created')).match(/[a-f0-9-]{36}/)![0]
  await send(`/item lock ${chest} item_lab ${rug}`, 'Matching key')
  await expect(inventory).not.toContainText('key')
  await send('open wooden chest', 'locked')
  await send('look under rug', 'You discover')
  await send('take wooden chest key', 'You take')
  await send('unlock wooden chest with wooden chest key', 'You unlock')
  await send('open wooden chest', 'You open')
  await page.reload()
  await expect(page.getByText(/Online/)).toBeVisible()
  await expect(inventory).toContainText('wooden chest key')
})
